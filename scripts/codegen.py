"""Publish this engine's protocol snapshot and regenerate its Python stubs.

``components/signals-protocol`` is the only text of the ``zndx`` protos.
``proto/inference/open_inference_grpc.proto`` is the federation OIP text until
that file lives in the protocol repo. This script copies both into
``signals_engine/proto``, generates ``signals_engine.wire``, and stamps
``PROTOCOL_SHA``. Peers import that snapshot. They do not vendor a second
protocol checkout.

Commit protocol edits in the submodule before running this. The stamp is the
submodule HEAD, and a dirty protocol tree would publish bytes that SHA does
not name.
"""

from __future__ import annotations

import hashlib
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
WIRE = ROOT / "src" / "signals_engine" / "wire"
PACKAGED = ROOT / "src" / "signals_engine" / "proto"
PROTOCOL_REPO = ROOT / "components" / "signals-protocol"
PROTOCOL = PROTOCOL_REPO / "proto"
OIP = ROOT / "proto" / "inference" / "open_inference_grpc.proto"
STAMP = ROOT / "src" / "signals_engine" / "protocol_stamp.py"

# grpc_tools emits absolute imports. Same-directory imports become relative.
# Cross-package imports (scheduler and agent use engine messages) stay absolute
# under signals_engine.wire so a host's own top-level ``zndx`` package is not
# required.
_FROM_IMPORT = re.compile(
    r"^from ((?:zndx(?:\.\w+)+)|inference) import (\w+) as",
    re.MULTILINE,
)
_IMPORT_MODULE = re.compile(
    r"^import ((?:zndx(?:\.\w+)+)|inference)\.(\w+) as",
    re.MULTILINE,
)
_LEFTOVER = re.compile(r"^(?:from|import) (?:zndx|inference)\b", re.MULTILINE)


def _protocol_sha() -> str:
    if not (PROTOCOL_REPO / ".git").exists() and not (ROOT / ".git").exists():
        raise SystemExit(f"codegen: {PROTOCOL_REPO} is not the signals-protocol checkout")
    dirty = subprocess.run(
        ["git", "-C", str(PROTOCOL_REPO), "status", "--porcelain"],
        check=True,
        capture_output=True,
        text=True,
    )
    if dirty.stdout.strip():
        raise SystemExit(
            "codegen: signals-protocol has uncommitted changes. "
            "Commit them on trunk, then run just gen so PROTOCOL_SHA names these bytes."
        )
    sha = subprocess.run(
        ["git", "-C", str(PROTOCOL_REPO), "rev-parse", "HEAD"],
        check=True,
        capture_output=True,
        text=True,
    )
    return sha.stdout.strip()


def _export_protos(sha: str) -> None:
    if not (PROTOCOL / "zndx" / "engine" / "v1" / "engine.proto").is_file():
        raise SystemExit(f"codegen: missing engine.proto under {PROTOCOL}")
    if not OIP.is_file():
        raise SystemExit(f"codegen: missing {OIP}")
    if PACKAGED.exists():
        shutil.rmtree(PACKAGED)
    for src in sorted(PROTOCOL.rglob("*.proto")):
        target = PACKAGED / src.relative_to(PROTOCOL)
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src, target)
    oip_target = PACKAGED / "inference" / "open_inference_grpc.proto"
    oip_target.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(OIP, oip_target)
    (PACKAGED / "SNAPSHOT.txt").write_text(
        "Generated by scripts/codegen.py. Do not edit these copies.\n"
        f"signals-protocol {sha}\n"
        "OIP source: proto/inference/open_inference_grpc.proto in signals-engine.\n"
        "Change the zndx protos in components/signals-protocol, commit, then just gen.\n"
    )


def _generate() -> None:
    if WIRE.exists():
        shutil.rmtree(WIRE)
    WIRE.mkdir(parents=True)
    protos = sorted(PACKAGED.rglob("*.proto"))
    if not protos:
        raise SystemExit(f"codegen: no protos under {PACKAGED}")
    cmd = [
        sys.executable,
        "-m",
        "grpc_tools.protoc",
        f"-I{PACKAGED}",
        f"--python_out={WIRE}",
        f"--grpc_python_out={WIRE}",
        f"--pyi_out={WIRE}",
        *[str(path) for path in protos],
    ]
    subprocess.run(cmd, check=True)


def _rewrite(text: str, path: Path) -> str:
    def repl(module: str, name: str) -> str:
        dest = WIRE.joinpath(*module.split("."))
        if path.parent == dest:
            return f"from . import {name} as"
        return f"from signals_engine.wire.{module} import {name} as"

    text = _FROM_IMPORT.sub(lambda m: repl(m.group(1), m.group(2)), text)
    text = _IMPORT_MODULE.sub(lambda m: repl(m.group(1), m.group(2)), text)
    return text


def _fix_imports() -> None:
    leftovers: list[str] = []
    for path in sorted(WIRE.rglob("*")):
        if path.suffix not in {".py", ".pyi"} or path.name == "__init__.py":
            continue
        text = path.read_text()
        fixed = _rewrite(text, path)
        if _LEFTOVER.search(fixed):
            leftovers.append(str(path.relative_to(ROOT)))
        if fixed != text:
            path.write_text(fixed)
    if leftovers:
        raise SystemExit("codegen: unrewritten zndx/inference imports in " + ", ".join(leftovers))


def _markers() -> None:
    directories = [WIRE, *[path for path in WIRE.rglob("*") if path.is_dir()]]
    for directory in directories:
        marker = directory / "__init__.py"
        if not marker.exists():
            marker.write_text('"""Generated wire package. Do not edit by hand."""\n')


def _stamp(sha: str) -> None:
    oip_sha = hashlib.sha256(OIP.read_bytes()).hexdigest()
    STAMP.write_text(
        '"""Generated by scripts/codegen.py. Do not edit by hand."""\n\n'
        f'PROTOCOL_SHA = "{sha}"\n'
        f'OIP_SHA256 = "{oip_sha}"\n'
    )


def main() -> None:
    sha = _protocol_sha()
    _export_protos(sha)
    _generate()
    _markers()
    _fix_imports()
    _stamp(sha)
    print(f"codegen: protocol {sha[:12]} packaged at {PACKAGED.relative_to(ROOT)}")
    print(f"codegen: stubs at {WIRE.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
